// TestExampleFixtureTransport proves the explicit accommodation for
// pascalandy/nicely#496. Once binary fixtures round-trip exactly, remove the
// newline-ending constraint and this transport-specific test. Keep the real
// example shrink and independent pixel/privacy checks in acceptance.txtar.
func TestExampleFixtureTransport(t *testing.T) {
	generated := exampleWebP(t)
	if generated[len(generated)-1] != '\n' {
		t.Fatal("the #496 accommodation requires an existing final newline")
	}
	archive, err := txtar.ParseFile("testdata/examples.txtar")
	if err != nil {
		t.Fatal(err)
	}
	if len(archive.Files) != 1 || archive.Files[0].Name != "example.webp" || !bytes.Equal(archive.Files[0].Data, generated) {
		t.Fatal("txtar changed the generated example image bytes")
	}
	decoded, format, err := image.Decode(bytes.NewReader(generated))
	if err != nil || format != "webp" || decoded.Bounds().Dx() != 64 || decoded.Bounds().Dy() != 32 {
		t.Fatalf("example is not the generated 64 by 32 WebP: %v", err)
	}
	// A second archive carries these same bytes into the actual shrink case.
	scenario, err := txtar.ParseFile("testdata/script/acceptance.txtar")
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range scenario.Files {
		if file.Name == "example.webp" && bytes.Equal(file.Data, generated) {
			return
		}
	}
	t.Fatal("the acceptance scenario does not exercise the manifest example image")
}

