// This helper is only used to regenerate the two checked-in archives below.
// The test checks their bytes, and acceptance.txtar checks the real command.
func TestWriteExampleFixture(t *testing.T) {
	if os.Getenv("NCLY_REGENERATE_EXAMPLE") != "1" {
		t.Skip("set NCLY_REGENERATE_EXAMPLE=1 to regenerate the example archives")
	}
	data := exampleWebP(t)
	archive := &txtar.Archive{Comment: []byte("# Generated by exampleWebP in example_test.go. See nicely#496.\n"), Files: []txtar.File{{Name: "example.webp", Data: data}}}
	if err := os.WriteFile("testdata/examples.txtar", txtar.Format(archive), 0o644); err != nil {
		t.Fatal(err)
	}
	scenario, err := txtar.ParseFile("testdata/script/acceptance.txtar")
	if err != nil {
		t.Fatal(err)
	}
	files := scenario.Files[:0]
	for _, file := range scenario.Files {
		if file.Name != "example.webp" {
			files = append(files, file)
		}
	}
	scenario.Files = append(files[:0:0], txtar.File{Name: "example.webp", Data: data})
	scenario.Files = append(scenario.Files, files...)
	if err := os.WriteFile("testdata/script/acceptance.txtar", txtar.Format(scenario), 0o644); err != nil {
		t.Fatal(err)
	}
}
